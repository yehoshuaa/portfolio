function getSavedLanguage() {
  return localStorage.getItem("selectedLanguage") || "nl";
}

function translate(key, replacements = {}, language = getSavedLanguage()) {
  const dictionary = translations[language] || translations.nl;
  let text = dictionary[key] || translations.nl[key] || key;

  Object.entries(replacements).forEach(([replacementKey, replacementValue]) => {
    text = text.replaceAll(`{${replacementKey}}`, replacementValue);
  });

  return text;
}

function applyTranslatedAttributes(language) {
  document.querySelectorAll("[data-translate]").forEach((element) => {
    const key = element.getAttribute("data-translate");
    element.textContent = translate(key, {}, language);
  });

  document.querySelectorAll("[data-translate-placeholder]").forEach((element) => {
    const key = element.getAttribute("data-translate-placeholder");
    element.setAttribute("placeholder", translate(key, {}, language));
  });

  document.querySelectorAll("[data-translate-aria-label]").forEach((element) => {
    const key = element.getAttribute("data-translate-aria-label");
    element.setAttribute("aria-label", translate(key, {}, language));
  });

  document.querySelectorAll("[data-translate-title]").forEach((element) => {
    const key = element.getAttribute("data-translate-title");
    element.setAttribute("title", translate(key, {}, language));
  });
}

function applyLanguage(language) {
  document.documentElement.lang = language;
  applyTranslatedAttributes(language);

  const languageSelect = document.getElementById("languageSelect");
  if (languageSelect) {
    languageSelect.value = language;
  }

  const profileLanguageSelect = document.getElementById("profileLanguageSelect");
  if (profileLanguageSelect) {
    profileLanguageSelect.value = language;
  }

  document.dispatchEvent(new CustomEvent("languageChanged", { detail: { language } }));
}

function setLanguage(language) {
  localStorage.setItem("selectedLanguage", language);
  applyLanguage(language);
}

window.translate = translate;
window.applyLanguage = applyLanguage;
window.setLanguage = setLanguage;
window.getSavedLanguage = getSavedLanguage;

document.addEventListener("DOMContentLoaded", () => {
  applyLanguage(getSavedLanguage());
});
